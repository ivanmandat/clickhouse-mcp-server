-- Четыре слоя хранилища. Комментарии к базам и таблицам — не украшение:
-- именно их читает интроспекция MCP, когда агент выясняет, куда можно ходить.

CREATE DATABASE IF NOT EXISTS raw
    COMMENT 'Слой 1 (raw). Сырые выгрузки из источников как есть: всё строками, дубли не убраны, значения не нормализованы. Для отчётов не использовать.';

CREATE DATABASE IF NOT EXISTS `int`
    COMMENT 'Слой 2 (int). Промежуточные преобразования: типизация, дедупликация, нормализация значений. Служебный слой, напрямую в дашбордах не использовать.';

CREATE DATABASE IF NOT EXISTS core
    COMMENT 'Слой 3 (core). Очищенные типизированные витрины для аналитиков. Минимум бизнес-логики: факты и измерения без предрасчитанных метрик.';

CREATE DATABASE IF NOT EXISTS mart
    COMMENT 'Слой 4 (mart). OBT и агрегаты под дашборды. Основной слой для построения виджетов.';
